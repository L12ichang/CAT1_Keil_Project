#include "sys_time.h"
#include "sys_tick.h"

static volatile u32 _time_ms;

/************************************
功能描述：初始化单调毫秒时间基准
输入参数：无
输出返回：无
*************************************/
void sys_time_init(void)
{
    _time_ms = HAL_GetTick();
}


/************************************
功能描述：在 SysTick 中断中推进单调毫秒时间
输入参数：无
输出返回：无
注意：阶段 8 删除旧 Portable 时间基准适配。
*************************************/
void sys_time_tick_isr(void)
{
    _time_ms++;
    sys_tick_legacy_timebase_isr();
}


/************************************
功能描述：读取当前单调毫秒时间
输入参数：无
输出返回：当前毫秒时间
*************************************/
u32 sys_time_get_ms(void)
{
    return _time_ms;
}


/************************************
功能描述：判断绝对毫秒到期时间是否已经到达
输入参数：now_ms 当前毫秒时间，due_ms 绝对到期毫秒时间
输出返回：到期返回 BOOL_TRUE，否则返回 BOOL_FALSE
*************************************/
boolean_en sys_time_is_due(u32 now_ms, u32 due_ms)
{
    if ((s32)(now_ms - due_ms) >= 0)
    {
        return BOOL_TRUE;
    }

    return BOOL_FALSE;
}


/************************************
功能描述：计算从指定时刻至今经过的毫秒数
输入参数：start_ms 起始毫秒时间
输出返回：经过的毫秒数
*************************************/
u32 sys_time_elapsed_ms(u32 start_ms)
{
    return sys_time_get_ms() - start_ms;
}
