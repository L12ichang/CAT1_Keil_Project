#ifndef __SYS_TIME_H__
#define __SYS_TIME_H__

#include "common.h"

/************************************
功能描述：初始化单调毫秒时间基准
输入参数：无
输出返回：无
*************************************/
extern void sys_time_init(void);

/************************************
功能描述：在 SysTick 中断中推进单调毫秒时间
输入参数：无
输出返回：无
注意：只允许维护时间基准和阶段 8 删除的旧时间基准适配。
*************************************/
extern void sys_time_tick_isr(void);

/************************************
功能描述：读取当前单调毫秒时间
输入参数：无
输出返回：当前毫秒时间
*************************************/
extern u32 sys_time_get_ms(void);

/************************************
功能描述：判断绝对毫秒到期时间是否已经到达
输入参数：now_ms 当前毫秒时间，due_ms 绝对到期毫秒时间
输出返回：到期返回 BOOL_TRUE，否则返回 BOOL_FALSE
*************************************/
extern boolean_en sys_time_is_due(u32 now_ms, u32 due_ms);

/************************************
功能描述：计算从指定时刻至今经过的毫秒数
输入参数：start_ms 起始毫秒时间
输出返回：经过的毫秒数
*************************************/
extern u32 sys_time_elapsed_ms(u32 start_ms);

#endif
